bool validModelGamePath(const QString &path)
{
	static const QRegularExpression pattern(QStringLiteral("^[A-Za-z0-9_][A-Za-z0-9_./-]*$"));
	return path.size() <= 255 && pattern.match(path).hasMatch() && !path.contains(QStringLiteral("..")) && !path.contains(QStringLiteral("//"));
}

QString modelDoom3ModelDefText(const ModelMesh &mesh, const ModelDoom3DefOptions &o, QString *error)
{
	static const QRegularExpression declName(QStringLiteral("^[A-Za-z_][A-Za-z0-9_./-]{0,127}$"));
	if (!declName.match(o.name).hasMatch() || (!o.inherit.isEmpty() && !declName.match(o.inherit).hasMatch()))
	{
		fail(error, Text::tr("A model declaration name is ASCII letters, digits, underscores, dots, slashes or hyphens, starting with a letter "
							 "or underscore."));
		return {};
	}
	if (!validModelGamePath(o.meshPath) || !o.meshPath.endsWith(QStringLiteral(".md5mesh"), Qt::CaseInsensitive) ||
		(!o.animDirectory.isEmpty() && !validModelGamePath(o.animDirectory)) || (!o.skin.isEmpty() && !validModelGamePath(o.skin)))
	{
		fail(error, Text::tr("Use game-relative paths with forward slashes, such as models/md5/monsters/imp/imp.md5mesh, without spaces or "
							 "\"..\"."));
		return {};
	}
	for (double value : o.offset)
		if (!std::isfinite(value) || std::abs(value) > 1000000)
		{
			fail(error, Text::tr("The offset must be three finite numbers."));
			return {};
		}
	QStringList lines{QStringLiteral("// ") + generatedLine(o.sourceName), QString(), QStringLiteral("model %1 {").arg(o.name)};
	if (!o.inherit.isEmpty())
		lines << QStringLiteral("\tinherit\t%1").arg(o.inherit);
	lines << QStringLiteral("\tmesh\t%1").arg(o.meshPath);
	if (!o.skin.isEmpty())
		lines << QStringLiteral("\tskin\t%1").arg(o.skin);
	if (o.hasOffset)
		lines << QStringLiteral("\toffset\t( %1 %2 %3 )").arg(number(o.offset[0]), number(o.offset[1]), number(o.offset[2]));
	if (!mesh.skeleton.clips.isEmpty())
		lines << QString();
	QSet<QString> names;
	for (const auto &clip : mesh.skeleton.clips)
	{
		if (names.contains(clip.name.toLower()) || !validModelGamePath(clip.name))
		{
			fail(error, Text::tr("Clip %1 needs a unique name of ASCII letters, digits, underscores, dots or hyphens to be declared.").arg(clip.name));
			return {};
		}
		names.insert(clip.name.toLower());
		const auto path = animPath(o, clip.name);
		if (!validModelGamePath(path))
		{
			fail(error, Text::tr("The animation path %1 is not a game-relative path.").arg(path));
			return {};
		}
		if (clip.events.isEmpty())
		{
			lines << QStringLiteral("\tanim\t%1\t%2").arg(clip.name, path);
			continue;
		}
		QString problem;
		if (!validModelAnimationEvents(clip.events, int(clip.frames.size()), &problem))
		{
			fail(error, Text::tr("Clip %1: %2").arg(clip.name, problem));
			return {};
		}
		lines << QStringLiteral("\tanim\t%1\t%2 {").arg(clip.name, path);
		// Doom 3 numbers frames from one in declarations.
		for (const auto &event : sortedModelAnimationEvents(clip.events))
			lines << QStringLiteral("\t\tframe %1\t%2").arg(event.frame + 1).arg(modelAnimationEventCommandLine(event));
		lines << QStringLiteral("\t}");
	}
	lines << QStringLiteral("}") << QString();
	return lines.join(QLatin1Char('\n'));
}

bool modelDoom3ModelSet(const ModelMesh &mesh, const ModelDoom3DefOptions &o, QVector<ModelGameFile> *files, QString *error,
						const ModelWorkControl &control)
{
	ModelWorkProgress work(control, ModelWorkPhase::Serializing, error);
	if (!files || !work.check())
		return false;
	const auto text = modelDoom3ModelDefText(mesh, o, error);
	if (text.isEmpty())
		return false;
	QVector<ModelGameFile> result;
	const auto meshBytes = exportEditableModel(mesh, QStringLiteral("md5mesh"), ModelExportOptions{}, error, control);
	if (meshBytes.isEmpty())
		return false;
	result.append({o.meshPath, meshBytes, QStringLiteral("mesh")});
	for (int clip = 0; clip < mesh.skeleton.clips.size(); ++clip)
	{
		if (!work.check())
			return false;
		ModelExportOptions options;
		options.clip = clip;
		QString problem;
		const auto bytes = exportEditableModel(mesh, QStringLiteral("md5anim"), options, &problem, control);
		if (bytes.isEmpty())
			return fail(error, Text::tr("Clip %1 cannot be written as an md5anim: %2").arg(mesh.skeleton.clips[clip].name, problem));
		result.append({animPath(o, mesh.skeleton.clips[clip].name), bytes, QStringLiteral("anim")});
	}
	auto defName = o.name;
	defName.replace(QLatin1Char('/'), QLatin1Char('_'));
	result.append({QStringLiteral("def/%1.def").arg(defName), text.toUtf8(), QStringLiteral("declaration")});
	QSet<QString> paths;
	for (const auto &file : result)
	{
		if (paths.contains(file.path.toLower()))
			return fail(error, Text::tr("Two files of the model set would both be written to %1.").arg(file.path));
		paths.insert(file.path.toLower());
	}
	*files = std::move(result);
	return work.check();
}

QString modelQuakeCFrameMacrosText(const ModelMesh &mesh, const ModelQuakeCFrameOptions &o, QString *error)
{
	if ((!o.modelDirectory.isEmpty() && !validModelGamePath(o.modelDirectory)) || !identifier(o.base) || !identifier(o.skin))
	{
		fail(error, Text::tr("Use a game-relative $cd folder and $base and $skin names made of letters, digits and underscores."));
		return {};
	}
	if (mesh.frames.isEmpty() || !uniqueFrameNames(mesh, quakeCName, error))
	{
		if (mesh.frames.isEmpty())
			fail(error, Text::tr("The model has no frames to declare."));
		return {};
	}
	QStringList lines{QStringLiteral("/*"), QStringLiteral("=============================================================================="),
					  QString(), generatedLine(o.sourceName), QString(),
					  QStringLiteral("=============================================================================="), QStringLiteral("*/"),
					  QString()};
	if (!o.modelDirectory.isEmpty())
		lines << QStringLiteral("$cd %1").arg(o.modelDirectory);
	lines << QStringLiteral("$base %1").arg(o.base) << QStringLiteral("$skin %1").arg(o.skin);
	for (const auto &group : frameGroups(mesh))
	{
		lines << QString() << QStringLiteral("// ") + groupTitle(mesh, group);
		QStringList names;
		for (int f = group.first; f < group.first + group.count; ++f)
		{
			names << mesh.frames[f].name;
			if (names.size() == 10)
			{
				lines << QStringLiteral("$frame ") + names.join(QLatin1Char(' '));
				names.clear();
			}
		}
		if (!names.isEmpty())
			lines << QStringLiteral("$frame ") + names.join(QLatin1Char(' '));
		if (group.animation >= 0)
			for (const auto &event : sortedModelAnimationEvents(mesh.animations[group.animation].events))
				lines << QStringLiteral("// event on %1: %2")
							 .arg(mesh.frames.value(mesh.animations[group.animation].firstFrame + event.frame).name, modelAnimationEventCommandLine(event));
	}
	lines << QString();
	return lines.join(QLatin1Char('\n'));
}

QString modelQuake2FrameHeaderText(const ModelMesh &mesh, const ModelQuake2FrameOptions &o, QString *error)
{
	if ((!o.modelDirectory.isEmpty() && !validModelGamePath(o.modelDirectory)) || !identifier(o.prefix) || !std::isfinite(o.scale) ||
		o.scale <= 0 || o.scale > 1000)
	{
		fail(error, Text::tr("Use a game-relative model folder, a prefix made of letters, digits and underscores, and a positive scale."));
		return {};
	}
	if (mesh.frames.isEmpty() || !uniqueFrameNames(mesh, quake2Name, error))
	{
		if (mesh.frames.isEmpty())
			fail(error, Text::tr("The model has no frames to declare."));
		return {};
	}
	QStringList lines;
	if (!o.modelDirectory.isEmpty())
		lines << QStringLiteral("// %1").arg(o.modelDirectory) << QString();
	lines << QStringLiteral("// ") + generatedLine(o.sourceName) << QStringLiteral("// %1 frames").arg(mesh.frames.size());
	for (const auto &group : frameGroups(mesh))
	{
		lines << QString() << QStringLiteral("// ") + groupTitle(mesh, group);
		for (int f = group.first; f < group.first + group.count; ++f)
		{
			const auto name = o.prefix + mesh.frames[f].name;
			lines << QStringLiteral("#define %1%2%3").arg(name, QString(std::max<qsizetype>(1, 24 - name.size()), QLatin1Char(' ')), QString::number(f));
		}
	}
	lines << QString() << QStringLiteral("#define MODEL_SCALE\t\t%1").arg(QString::number(o.scale, 'f', 6)) << QString();
	return lines.join(QLatin1Char('\n'));
}

QString modelGzdoomModeldefText(const ModelMesh &mesh, const ModelGzdoomModeldefOptions &o, QString *error)
{
	static const QRegularExpression sprite(QStringLiteral("^[A-Z0-9_]{3}$"));
	if (!identifier(o.actor) || !sprite.match(o.sprite).hasMatch())
	{
		fail(error, Text::tr("Name the actor class with letters, digits and underscores, and give three upper-case letters or digits for the "
							 "sprite names."));
		return {};
	}
	if (!quotable(o.path) || !quotable(o.model) || (!o.skin.isEmpty() && !quotable(o.skin)))
	{
		fail(error, Text::tr("The path, model and skin must be printable text without quotes or backslashes."));
		return {};
	}
	for (double value : {o.scale[0], o.scale[1], o.scale[2], o.offset[0], o.offset[1], o.offset[2], o.angleOffset})
		if (!std::isfinite(value) || std::abs(value) > 1000000)
		{
			fail(error, Text::tr("Scale, offset and angle must be finite numbers."));
			return {};
		}
	if (mesh.frames.isEmpty())
	{
		fail(error, Text::tr("The model has no frames to declare."));
		return {};
	}
	// GZDoom sprite frames run A-Z then [, \ and ]: 29 per sprite name.
	static const QString letters = QStringLiteral("ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]");
	static const QString codes = QStringLiteral("0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ");
	QStringList summary, frames;
	int block = 0;
	for (const auto &group : frameGroups(mesh))
	{
		QStringList names;
		for (int offset = 0; offset < group.count; offset += int(letters.size()))
		{
			if (block >= codes.size())
			{
				fail(error, Text::tr("The model needs more than 36 sprite names. Declare fewer frames or split the model."));
				return {};
			}
			const auto name = o.sprite + codes[block++];
			const int count = std::min(int(letters.size()), group.count - offset);
			names << QStringLiteral("%1 %2-%3").arg(name, QString(letters[0]), QString(letters[count - 1]));
			for (int i = 0; i < count; ++i)
				frames << QStringLiteral("\tFrameIndex %1 %2 0 %3").arg(name, QString(letters[i])).arg(group.first + offset + i);
		}
		summary << QStringLiteral("// %1: %2").arg(group.animation < 0 ? QStringLiteral("frames %1-%2").arg(group.first).arg(group.first + group.count - 1)
																		: mesh.animations[group.animation].name,
												   names.join(QStringLiteral(", ")));
	}
	QStringList lines{QStringLiteral("// ") + generatedLine(o.sourceName),
					  QStringLiteral("// Sprite frames for the actor's states, by animation:")};
	lines << summary << QStringLiteral("Model %1").arg(o.actor) << QStringLiteral("{") << QStringLiteral("\tPath \"%1\"").arg(o.path)
		  << QStringLiteral("\tModel 0 \"%1\"").arg(o.model);
	if (!o.skin.isEmpty())
		lines << QStringLiteral("\tSkin 0 \"%1\"").arg(o.skin);
	lines << QStringLiteral("\tScale %1 %2 %3").arg(number(o.scale[0]), number(o.scale[1]), number(o.scale[2]));
	if (o.offset != std::array<double, 3>{})
		lines << QStringLiteral("\tOffset %1 %2 %3").arg(number(o.offset[0]), number(o.offset[1]), number(o.offset[2]));
	if (o.angleOffset != 0)
		lines << QStringLiteral("\tAngleOffset %1").arg(number(o.angleOffset));
	lines << QString() << frames << QStringLiteral("}") << QString();
	return lines.join(QLatin1Char('\n'));
}
QString modelGzdoomVoxeldefText(const ModelMesh &mesh, const ModelGzdoomVoxeldefOptions &o, QString *error)
{
	// GZDoom draws voxels unanimated; the declaration names the .kvx file the
	// package ships (VibeStudio reads KVX but does not write it).
	if (mesh.frames.size() > 1 || !mesh.skeleton.clips.isEmpty())
	{
		fail(error, Text::tr("VOXELDEF voxels are not animated. Declare a model with a single frame, such as a KVX voxel."));
		return {};
	}
	// Four-character sprites, or a sprite and one frame letter (A-Z, [, \, ]).
	static const QRegularExpression sprite(QStringLiteral("^[A-Z0-9_]{4}[A-Z\\[\\\\\\]]?$"));
	QSet<QString> seen;
	for (const auto &name : o.sprites)
		if (!sprite.match(name).hasMatch() || seen.contains(name))
		{
			fail(error, Text::tr("Give each replaced sprite once, as four upper-case letters or digits, optionally followed by a frame letter."));
			return {};
		}
		else
			seen.insert(name);
	if (o.sprites.isEmpty() || o.sprites.size() > 256)
	{
		fail(error, Text::tr("Name from 1 to 256 sprites for the voxel to replace."));
		return {};
	}
	if (!validModelGamePath(o.path) || !o.path.endsWith(QStringLiteral(".kvx"), Qt::CaseInsensitive))
	{
		fail(error, Text::tr("Give the voxel's package path as letters, digits and '/', ending in .kvx, such as voxels/troo.kvx."));
		return {};
	}
	if (!std::isfinite(o.scale) || o.scale <= 0 || o.scale > 1000 || !std::isfinite(o.angleOffset) || std::abs(o.angleOffset) > 360 ||
		std::abs(o.placedSpin) > 3600 || std::abs(o.droppedSpin) > 3600)
	{
		fail(error, Text::tr("Use a scale above 0 up to 1000, an angle offset from -360 to 360 and spins from -3600 to 3600."));
		return {};
	}
	// The scale is read as a floating-point number: keep a decimal point.
	auto scale = number(o.scale);
	if (!scale.contains(QLatin1Char('.')) && !scale.contains(QLatin1Char('e')))
		scale += QStringLiteral(".0");
	QStringList options;
	if (o.scale != 1)
		options << QStringLiteral("\tScale = %1").arg(scale);
	if (o.angleOffset != 0)
		options << QStringLiteral("\tAngleOffset = %1").arg(number(o.angleOffset));
	if (o.placedSpin == o.droppedSpin && o.placedSpin != 0)
		options << QStringLiteral("\tSpin = %1").arg(o.placedSpin);
	else
	{
		if (o.placedSpin != 0)
			options << QStringLiteral("\tPlacedSpin = %1").arg(o.placedSpin);
		if (o.droppedSpin != 0)
			options << QStringLiteral("\tDroppedSpin = %1").arg(o.droppedSpin);
	}
	if (o.overridePalette)
		options << QStringLiteral("\tOverridePalette");
	QStringList lines{QStringLiteral("// ") + generatedLine(o.sourceName)};
	for (const auto &name : o.sprites)
	{
		lines << QStringLiteral("%1 = \"%2\"").arg(name, o.path);
		if (!options.isEmpty())
			lines << QStringLiteral("{") << options << QStringLiteral("}");
	}
	lines << QString();
	return lines.join(QLatin1Char('\n'));
}
bool stageModelGameFiles(const QVector<ModelGameFile> &files, PackageStagingModel *staging, bool replaceExisting, QString *error)
{
	if (files.isEmpty())
		return fail(error, Text::tr("Prepare the model set before staging it."));
	if (!staging || !staging->isLoaded() || staging->sourceFormat() == PackageArchiveFormat::Wad)
		return fail(error, Text::tr("Open a folder, ZIP, PK3 or PK4 package before staging the model set."));
	auto staged = *staging;
	if (!staged.beginOperationGroup(Text::tr("Stage Doom 3 model set"), error))
		return false;
	for (const auto &file : files)
	{
		const auto normalized = normalizePackageVirtualPath(file.path, false);
		const auto suffix = QFileInfo(normalized.normalizedPath).suffix().toLower();
		const bool known = (file.role == QStringLiteral("mesh") && suffix == QStringLiteral("md5mesh") && file.bytes.startsWith("MD5Version")) ||
						   (file.role == QStringLiteral("anim") && suffix == QStringLiteral("md5anim") && file.bytes.startsWith("MD5Version")) ||
						   (file.role == QStringLiteral("declaration") && suffix == QStringLiteral("def") && !file.bytes.isEmpty());
		if (!normalized.isSafe() || !validModelGamePath(normalized.normalizedPath) || !known || file.bytes.size() > modelDocumentMaxSourceBytes)
		{
			staged.endOperationGroup(false);
			return fail(error, Text::tr("%1 is not a model set file this package can take.").arg(file.path));
		}
		if (!staged.addBytes(file.bytes, normalized.normalizedPath, error,
							 replaceExisting ? PackageStageConflictResolution::ReplaceExisting : PackageStageConflictResolution::Block))
		{
			staged.endOperationGroup(false);
			return false;
		}
	}
	if (!staged.endOperationGroup(true, error))
		return false;
	if (!staged.summary().canSave)
		return fail(error, Text::tr("Resolve the package's staging conflicts before staging the model set."));
	*staging = std::move(staged);
	return true;
}
