bool fail(QString *error, const QString &message)
{
	if (error)
		*error = message;
	return false;
}
QString number(double value)
{
	return QString::number(value == 0 ? 0.0 : value, 'g', 9);
}
QString generatedLine(const QString &sourceName)
{
	return sourceName.isEmpty() ? QStringLiteral("Generated by VibeStudio. Edit the source and generate it again.")
								: QStringLiteral("Generated by VibeStudio from %1. Edit the source and generate it again.").arg(sourceName);
}
bool identifier(const QString &text)
{
	static const QRegularExpression pattern(QStringLiteral("^[A-Za-z_][A-Za-z0-9_]*$"));
	return pattern.match(text).hasMatch();
}
bool quotable(const QString &text)
{
	if (text.isEmpty() || text.size() > 255)
		return false;
	for (const QChar c : text)
		if (c.unicode() < 0x20 || c.unicode() > 0x7e || c == QLatin1Char('"') || c == QLatin1Char('\\'))
			return false;
	return true;
}
// Frames grouped in order by the first animation (by start frame) holding
// them; frames in no animation form unnamed groups.
struct FrameGroup
{
	int first = 0, count = 0;
	int animation = -1;
};
QVector<FrameGroup> frameGroups(const ModelMesh &mesh)
{
	QVector<int> order;
	for (int i = 0; i < mesh.animations.size(); ++i)
		order.append(i);
	std::stable_sort(order.begin(), order.end(), [&](int a, int b) { return mesh.animations[a].firstFrame < mesh.animations[b].firstFrame; });
	QVector<int> owner(mesh.frames.size(), -1);
	for (int index : order)
	{
		const auto &animation = mesh.animations[index];
		for (int f = animation.firstFrame; f < animation.firstFrame + animation.frameCount && f < owner.size(); ++f)
			if (f >= 0 && owner[f] < 0)
				owner[f] = index;
	}
	QVector<FrameGroup> groups;
	for (int f = 0; f < owner.size(); ++f)
	{
		if (groups.isEmpty() || groups.last().animation != owner[f] ||
			(owner[f] >= 0 && f == mesh.animations[owner[f]].firstFrame && groups.last().count > 0))
			groups.append({f, 0, owner[f]});
		++groups.last().count;
	}
	return groups;
}
QString groupTitle(const ModelMesh &mesh, const FrameGroup &group)
{
	const auto range = group.count == 1 ? QStringLiteral("frame %1").arg(group.first)
										: QStringLiteral("frames %1-%2").arg(group.first).arg(group.first + group.count - 1);
	return group.animation < 0 ? QStringLiteral("outside every animation: %1").arg(range)
							   : QStringLiteral("%1: %2").arg(mesh.animations[group.animation].name, range);
}
bool uniqueFrameNames(const ModelMesh &mesh, bool (*valid)(const QString &), QString *error)
{
	QSet<QString> seen;
	for (int f = 0; f < mesh.frames.size(); ++f)
	{
		const auto &name = mesh.frames[f].name;
		if (!valid(name))
			return fail(error, Text::tr("Frame %1 is named \"%2\", which game code cannot use as a name. Rename it with letters, digits and "
										"underscores, starting with a letter or underscore.")
								   .arg(f)
								   .arg(name));
		if (seen.contains(name.toLower()))
			return fail(error, Text::tr("Two frames are named %1. Give every frame its own name.").arg(name));
		seen.insert(name.toLower());
	}
	return true;
}
bool quake2Name(const QString &name)
{
	static const QRegularExpression pattern(QStringLiteral("^[A-Za-z0-9_]+$"));
	return pattern.match(name).hasMatch();
}
bool quakeCName(const QString &name)
{
	return identifier(name);
}
QString animPath(const ModelDoom3DefOptions &o, const QString &clip)
{
	auto directory = o.animDirectory;
	if (directory.isEmpty())
		directory = o.meshPath.section(QLatin1Char('/'), 0, -2);
	while (directory.endsWith(QLatin1Char('/')))
		directory.chop(1);
	return (directory.isEmpty() ? QString() : directory + QLatin1Char('/')) + clip + QStringLiteral(".md5anim");
}
